'use strict'
const { test } = require('node:test')
const assert = require('node:assert/strict')
const vm = require('node:vm')
const fs = require('node:fs')
const path = require('node:path')
const { Arbiter, allows, canReplace } = require('../src/core/motion-arbitration')
const { DEFAULT_SETTINGS } = require('../src/core/config')

test('調停は初期OFFで、口や瞬きと姿勢の動作を独立に扱う', () => {
  assert.equal(DEFAULT_SETTINGS.features.motionArbitration, false)
  assert.equal(allows('autonomy', 'idle', false), true)
  assert.equal(allows('autonomy', 'speaking', true), false)
  assert.equal(allows('thinking', 'thinking', false), true)
  assert.equal(allows('reaction', 'speaking', true), false)
  assert.equal(allows('filler', 'thinking', true), true)
  assert.equal(canReplace('speech', 'autonomy'), false)
  assert.equal(canReplace('autonomy', 'speech'), true)
})
test('姿勢は現在値から滑らかに移り、異常値を上限内に保つ', () => {
  const a = new Arbiter({ ParamAngleX:0, ParamAngleY:0, ParamAngleZ:0, ParamBodyAngleX:0, ParamBodyAngleY:0, ParamBodyAngleZ:0 })
  const target = { ParamAngleX:100, ParamAngleY:-100, ParamAngleZ:12, ParamBodyAngleX:99, ParamBodyAngleY:0, ParamBodyAngleZ:0, ParamBreath:0.8 }
  const p = a.smooth(target, 0.016)
  assert.ok(p.ParamAngleX > 0 && p.ParamAngleX < 30)
  assert.ok(p.ParamBodyAngleX > 0 && p.ParamBodyAngleX < 10)
  assert.equal(p.ParamBreath, 0.8)
  const q = a.smooth(target, 0.016)
  assert.ok(q.ParamAngleX > p.ParamAngleX && q.ParamAngleX < 30)
})
test('既存ポーズの範囲外seedをLive2D安全範囲へ収める', () => {
  const a = new Arbiter({ ParamAngleX:80, ParamAngleY:-80, ParamAngleZ:0,
    ParamBodyAngleX:50, ParamBodyAngleY:0, ParamBodyAngleZ:0 })
  const p = a.smooth({ ParamAngleX:0, ParamAngleY:0, ParamAngleZ:0,
    ParamBodyAngleX:0, ParamBodyAngleY:0, ParamBodyAngleZ:0 }, 0.016)
  assert.ok(Math.abs(p.ParamAngleX) <= 30)
  assert.ok(Math.abs(p.ParamAngleY) <= 30)
  assert.ok(Math.abs(p.ParamBodyAngleX) <= 10)
})
test('新世代は旧世代の中断により消されない', () => {
  const a = new Arbiter()
  a.begin('old'); a.begin('new')
  assert.equal(a.isCurrent('old'), false)
  assert.equal(a.cancel('old'), false)
  assert.equal(a.isCurrent('new'), true)
  assert.equal(a.cancel('new'), true)
  assert.equal(a.isCurrent('new'), false)
})
test('Live2Dの調停は自発動作を新しい会話から除き、無効化できる', () => {
  let now = 1000
  const context = { window: {}, performance: { now: () => now } }
  for (const file of ['../src/core/motion-arbitration.js', '../renderer/avatar-live2d.js'])
    vm.runInNewContext(fs.readFileSync(path.join(__dirname, file), 'utf8'), context)
  const avatar = new context.window.Live2DAvatar({})
  avatar.setMotionArbitrationEnabled(true)
  avatar.playMotion('bow', { source:'autonomy' })
  assert.equal(avatar.motion.source, 'autonomy')
  avatar.beginMotionTurn('new')
  assert.equal(avatar.motion, null)
  avatar.setState('thinking')
  avatar.playMotion('think', { source:'thinking', generationId:'old' })
  assert.equal(avatar.motion, null)
  avatar.playMotion('think', { source:'thinking', generationId:'new' })
  assert.equal(avatar.motion.name, 'think')
  avatar.playMotion('nod', { source:'reaction', generationId:'new' })
  assert.equal(avatar.motion, null)
  assert.equal(avatar.nod.source, 'reaction')
  avatar.playMotion('bow', { source:'speech', generationId:'new' })
  assert.equal(avatar.nod, null)
  assert.equal(avatar.motion.source, 'speech')
  avatar.playMotion('wave', { source:'manual', generationId:'new' })
  assert.equal(avatar.motion.name, 'bow')
  avatar.cancelMotionSource('speech', 'old')
  assert.equal(avatar.motion.source, 'speech')
  avatar.cancelMotionTurn('old')
  assert.equal(avatar.motion.name, 'bow')
  avatar.cancelMotionTurn('new')
  assert.equal(avatar.motion, null)
  avatar.setMotionArbitrationEnabled(false)
  assert.equal(avatar.motionArbiter, null)
})
